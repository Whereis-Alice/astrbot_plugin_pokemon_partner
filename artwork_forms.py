def sprite_for(row: Mapping[str, Any]) -> int | str | None:
    """Resolve an exact form without network requests or mutating the source row."""
    raw = row.get("id")
    if isinstance(raw, bool) or not str(raw).isascii() or not str(raw).isdecimal():
        return None
    dex = int(raw)
    if dex <= 0:
        return None
    form = unicodedata.normalize("NFKC", str(row.get("form_name") or "")).strip()
    if not form:
        return dex
    match = FORM_SPRITES.get((dex, form))
    if match is not None:
        return match
    # Support the dataset's older regional aliases without mixing other forms.
    region = form.removesuffix("的样子")
    if region in {"阿罗拉", "伽勒尔", "洗翠", "帕底亚"}:
        matches = {sprite for (number, label), sprite in FORM_SPRITES.items()
                   if number == dex and label.startswith(region)}
        return next(iter(matches)) if len(matches) == 1 else None
    return None


